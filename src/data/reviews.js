/**
 * Calculates statistics derived dynamically from the sample review dataset
 */
export function getReviewStats(items = reviews) {
  const total = items.length;
  if (total === 0) {
    return {
      total: 0,
      averageRating: 5.0,
      recommendPercent: 100,
      distribution: { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 },
    };
  }
  const sum = items.reduce((acc, r) => acc + (r.rating || 5), 0);
  const averageRating = Number((sum / total).toFixed(1));
  const recommendedCount = items.filter((r) => r.recommended !== false).length;
  const recommendPercent = Math.round((recommendedCount / total) * 100);
  const distribution = { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 };
  items.forEach((r) => {
    const star = Math.min(5, Math.max(1, Math.round(r.rating || 5)));
    distribution[star] = (distribution[star] || 0) + 1;
  });

  return {
    total,
    averageRating,
    recommendPercent,
    distribution,
  };
}

export const reviewSummary = getReviewStats(reviews);
